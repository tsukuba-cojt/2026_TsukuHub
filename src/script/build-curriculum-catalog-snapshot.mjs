import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ACADEMIC_YEARS = [2023, 2024, 2025, 2026];
const UNIVERSITY = "tsukuba";
const RETRIEVED_AT = "2026-10-16";
const expectedSourceHashes = new Map([
  [2023, "8aca44f7c164d35bbb4449a5198610260c96713a759de0d1f295d36127cbbeff"],
  [2024, "3a74de3ea118a85c420cf67728a42f7155c834f6afff8682b8d15142139fbe15"],
  [2025, "ed59d7f92b9faf6e60d9adbb7d50747027e4cdc9469b3a3e6154254205fdf13b"],
  [2026, "b46050ba62c0ffa989402ef688321144118ea461262a68534b529f8c04988ca5"],
]);
const courseCodePattern = /(?<![0-9A-Z])[0-9A-Z]{7}(?![0-9A-Z])/g;
const sameCoursePhrasePattern = /([^。\n]{0,160})と同一/g;
const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const courseDirectory = resolve(scriptDirectory, "../../public/data/courses");
const outputDirectory = resolve(
  scriptDirectory,
  "../features/graduationCheck/curriculum/catalog/snapshots",
);

const extractSameCourseCodes = (courseCode, remarks) => {
  const codes = new Set();
  for (const phrase of remarks.matchAll(sameCoursePhrasePattern)) {
    for (const rawCode of phrase[1].match(courseCodePattern) ?? []) {
      const code = rawCode.trim().toUpperCase();
      if (code !== courseCode) codes.add(code);
    }
  }
  return codes;
};

const buildLinks = (courses) => {
  const linkKeys = new Set();
  const links = [];
  for (const course of courses) {
    const courseCode = course.course_number.trim().toUpperCase();
    for (const sameCourseCode of extractSameCourseCodes(
      courseCode,
      course.remarks ?? "",
    )) {
      const pair = [courseCode, sameCourseCode].sort();
      const key = pair.join("\0");
      if (linkKeys.has(key)) continue;
      linkKeys.add(key);
      links.push({ courseCode: pair[0], sameCourseCode: pair[1] });
    }
  }
  return links.sort((left, right) =>
    `${left.courseCode}\0${left.sameCourseCode}`.localeCompare(
      `${right.courseCode}\0${right.sameCourseCode}`,
    ),
  );
};

await mkdir(outputDirectory, { recursive: true });
for (const academicYear of ACADEMIC_YEARS) {
  const inputPath = resolve(
    courseDirectory,
    `${UNIVERSITY}-${academicYear}.json`,
  );
  const catalog = JSON.parse(await readFile(inputPath, "utf8"));
  const expectedHash = expectedSourceHashes.get(academicYear);
  if (
    catalog.academic_year !== academicYear ||
    catalog.source_sha256 !== expectedHash ||
    !catalog.repository_commit
  ) {
    throw new Error(`${inputPath}の年度・出典情報が一致しません。`);
  }

  const crossListingLinks = buildLinks(catalog.courses ?? []);
  const dateStamp = catalog.updated.replaceAll("-", "");
  const snapshot = {
    schemaVersion: "course-catalog-snapshot-1.0.0",
    academicYear,
    sourceDocument: {
      documentId: `tsukuba-kdb-course-catalog-${academicYear}-${dateStamp}`,
      fileName: catalog.source_url.split("/").at(-1),
      kind: "course_catalog_snapshot",
      editionYear: academicYear,
      sha256: catalog.source_sha256,
      sourceUrl: catalog.source_url,
      repositoryCommit: catalog.repository_commit,
      snapshotDate: catalog.updated,
      retrievedAt: RETRIEVED_AT,
      license: "MPL-2.0 (repository)",
      provenanceNote:
        "public/data/coursesの年度別固定JSONを基礎データとして生成した科目カタログスナップショット。",
    },
    sourceRowCount: catalog.source_row_count,
    courseCount: catalog.courses.length,
    skippedRowCount: catalog.skipped_row_count,
    duplicateCourseCodeCount: catalog.duplicate_course_code_count,
    parseWarningCount: catalog.parse_warning_count,
    crossListingLinks,
  };
  const outputPath = resolve(outputDirectory, `tsukuba${academicYear}.ts`);
  const generated =
    `// This file is generated by src/script/build-curriculum-catalog-snapshot.mjs.\n` +
    `// Source: public/data/courses/${UNIVERSITY}-${academicYear}.json\n` +
    `// Do not edit manually.\n\n` +
    `import type { CourseCatalogSnapshot } from "../types";\n\n` +
    `export const tsukuba${academicYear}CatalogSnapshot = ${JSON.stringify(snapshot, null, 2)} as const satisfies CourseCatalogSnapshot;\n`;
  await writeFile(outputPath, generated, "utf8");
  console.log(
    `Wrote ${academicYear}: ${crossListingLinks.length} links from ${catalog.courses.length} courses`,
  );
}
