## 頭の良さより「チームを前に進める力」が見られている

就職活動で初めてグループディスカッション、通称GDに参加すると、「何を話せばいいのか分からない」「発言できる人に負けそう」と不安になる人も多いでしょう。

筑波大学では、授業や研究で一人でじっくり考える機会が多い一方、限られた時間で初対面の学生と結論を出す経験は、それほど多くありません。

しかし、GDは話すのが得意な人だけが通過する選考ではありません。

企業が見ているのは、派手な発言や知識量ではなく、**周囲と協力しながら議論を前に進められるか**です。

## GDで評価されるのは「正解」ではない

GDでは、次のようなお題が出されます。

- 売上を伸ばす方法を考えてください
- 良いリーダーに必要な能力を3つ決めてください
- 大学生の利用者を増やす施策を提案してください

こうした問題には、基本的に一つの正解がありません。

そのため、企業は最終的な答えだけではなく、結論に至るまでの行動を見ています。

例えば、次のような力です。

- 相手の意見を理解する力
- 議論を整理する力
- 自分の考えを分かりやすく伝える力
- 時間内に結論を出す力
- チーム全体を巻き込む力

発言回数が最も多い人が通過するとは限りません。むしろ、他の人の話を遮ったり、自分の意見に固執したりすると、評価を下げる可能性があります。

GDは討論大会ではなく、チームで一つの成果物を作る場です。

## 最初の5分で議論の土台を作る

GDが始まったら、いきなりアイデアを出すのではなく、最初に進め方を確認しましょう。

おすすめの流れは次のとおりです。

1. 言葉の定義をそろえる
2. 目標を明確にする
3. 評価基準を決める
4. アイデアを出す
5. 比較して結論を決める

例えば、「大学生が働きたい企業の条件を3つ決めてください」というお題であれば、まず「働きたい」とは応募したい企業なのか、長く働きたい企業なのかを確認します。

次に、給与、成長環境、働き方、仕事内容などの候補を出し、どの基準で3つに絞るかを決めます。

この土台を作らずに議論を始めると、全員が異なる前提で話し続けることになります。人間は前提がずれたままでも驚くほど元気に議論できるので、最初の整理が重要です。

## 役職は無理に取らなくていい

GDには、司会、書記、タイムキーパー、発表者などの役割があります。

役職を担当すると動きやすくなりますが、司会を取れば必ず高く評価されるわけではありません。

司会を担当したのに、自分だけが話して周囲の意見を拾えなければ逆効果です。

役職がなくても、次の行動で十分に貢献できます。

- 話を短く整理する
- 発言していない人に話を振る
- 議論がずれたときに目的へ戻す
- 残り時間を確認する
- 対立する意見の共通点を見つける

例えば、議論が広がりすぎたときには、次のように発言できます。

一度、今回の目的に戻って候補を整理しませんか。

意見が対立したときには、

どちらも重要なので、効果と実現しやすさの2軸で比べてみましょう。

と提案できます。

こうした発言は、チームを前に進めるため、評価されやすい行動です。

## 発言するときは「結論・理由・具体例」

考えがまとまっていないまま長く話すと、他の参加者に意図が伝わりません。

発言するときは、次の順番を意識しましょう。

私は〇〇が重要だと考えます。 理由は△△だからです。 例えば、□□のようなケースが考えられます。

例えば、大学生向けサービスの利用者を増やす方法について話すなら、

私は、大学ごとの口コミを充実させる施策が有効だと考えます。学生は自分と近い立場の人の体験を参考にしやすいからです。例えば、学年や学類ごとの利用事例を掲載すると、自分に合う使い方を想像しやすくなります。

このように話すと、自分の考えを短時間で伝えられます。

## 筑波大生が活かせる強み

筑波大学生には、GDで活かせる経験が多くあります。

授業や研究で身につけた論理的思考は、議論を整理するときに役立ちます。研究活動では、仮説を立て、情報を集め、結果を検討するため、GDの問題解決にも応用できます。

また、学園祭、サークル、学生団体、チーム開発、アルバイトなどで、異なる考えを持つ人と協力した経験も強みになります。

ただし、考えることに集中しすぎて、発言するタイミングを逃さないよう注意が必要です。

完璧な意見が完成するまで待つのではなく、

まだ整理途中ですが、方向性としては〇〇だと思います。

と前置きして発言して構いません。

GDでは、頭の中にある優れた考えより、チームへ共有された途中の考えの方が役立ちます。

## GDで避けたい行動

特に注意したいのは、次のような行動です。

- 他人の発言を否定から始める
- 自分だけが長く話す
- 議論の目的から外れる
- 発言せず、最後まで聞くだけになる
- 時間切れまで結論を先延ばしにする

意見に反対するときは、

その考え方もあると思います。その上で、実現可能性の面では〇〇も考える必要がありそうです。

と、相手の意見を受け止めてから伝えましょう。

完全に同意する必要はありません。相手を否定せず、論点を前へ進めることが大切です。

## 本番前にできる練習

GDは、知識を暗記するより、実際に人と話して練習する方が上達します。

友人3〜5人で集まり、20分程度のお題に取り組んでみましょう。

練習後は、次の点を振り返ります。

- 発言の量は適切だったか
- 意見を分かりやすく伝えられたか
- 他の人の意見を拾えたか
- 時間内に結論を出せたか
- チームへどのような貢献をしたか

録音できる場合は、自分の話す長さや口癖を確認するのも効果的です。

筑波大学の友人だけで練習すると考え方が似る場合もあるため、就活イベントなどで他大学の学生とGDを経験すると、本番に近い練習になります。

## GD突破のために最も大切なこと

GDで最も重要なのは、自分が目立つことではありません。

チームの状況を見ながら、「今、議論を進めるために何が必要か」を考えることです。

議論が止まっていれば論点を出す。意見が散らばっていれば整理する。発言していない人がいれば話を振る。時間が足りなければ、結論を決めるよう促す。

こうした小さな行動の積み重ねが、チームへの貢献として評価されます。

完璧な意見を準備する必要はありません。

**結論を出す人ではなく、チームが結論へたどり着くのを助ける人になる。**

この意識を持つだけで、GDでの動き方は大きく変わります。
