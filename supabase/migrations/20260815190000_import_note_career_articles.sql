## 結論：本格的な就活は3年生から。準備は1、2年生から少しずつ

就職活動には、全員に共通する明確な「開始日」があるわけではありません。

政府が示す就職・採用活動の原則では、企業の広報活動は卒業年度に入る直前の3月1日以降、採用選考は卒業年度の6月1日以降、正式な内定日は10月1日以降とされています。一定の条件を満たす専門活用型インターンシップでは、6月より前に選考へ進む場合もあります。

ただし、実際には3年生の夏に行われるインターンシップが、その後の早期選考につながることもあります。

そのため、目安としては次のように考えるとよいでしょう。

- 1年生：大学生活の選択肢を広げる
- 2年生：興味のある仕事を探し始める
- 3年生：インターンや選考へ本格的に参加する
- 4年生：選考と卒業研究を両立する

就活は、ある日突然始まるイベントではありません。大学生活で経験したことを整理し、自分に合う進路を少しずつ探していく過程です。

## 大学1年生：就活よりも「経験を増やす」

1年生の段階では、業界研究や面接対策を本格的に始める必要はありません。

まずは大学生活に慣れ、興味のある授業や活動に参加することを優先しましょう。

### 1年生の準備リスト

- 興味のある授業を幅広く履修する
- サークル、学生団体、アルバイトなどに参加する
- プログラミング、語学、資格などを試してみる
- 大学内外のイベントへ参加する
- 自分が取り組んだことを簡単に記録する

筑波大学には、学類の授業だけでなく、他学群・他学類の学生と関われる機会もあります。最初から将来の仕事を一つに決めるより、さまざまな分野に触れて、自分が何に興味を持つのかを知ることが重要です。

また、活動を始めた理由、工夫したこと、失敗したことをメモしておくと、後の自己分析やエントリーシート作成に役立ちます。

立派な成果を書く必要はありません。

「なぜ参加したのか」「どこが難しかったのか」「次にどう改善したのか」を月に一度程度記録しておくだけでも十分です。

## 大学2年生：興味のある業界や仕事を探す

2年生になったら、少しずつ社会や仕事について調べ始めます。

ただし、企業名を暗記するような企業研究は必要ありません。

まずは「どのような仕事があるのか」「自分は何に興味があるのか」を知る段階です。

### 2年生の準備リスト

- 興味のある業界を3つ程度調べる
- 気になる企業や職種を保存する
- 短期・長期インターンを確認する
- 社会人や先輩の話を聞く
- これまでの大学生活を振り返る
- 自分の強みや苦手なことを言葉にする

例えば、「IT業界に興味がある」で止めず、エンジニア、営業、企画、マーケティング、コンサルタントなど、具体的な職種まで調べてみましょう。

同じ企業でも、職種によって仕事内容や求められる能力は大きく異なります。

余裕があれば、短期インターンや長期インターンへ参加するのも選択肢です。ただし、参加すること自体が目的にならないよう注意が必要です。

授業や課外活動を圧迫してまで大量のインターンへ応募するより、興味のある分野を一つ選び、実際の仕事を経験する方が意味があります。

筑波大学のキャリア支援チームでは、就職活動を始めた学生だけでなく、これから進路を考える学生も個別相談を利用できます。相談内容が整理できていない状態でも利用でき、インターン、進路選択、エントリーシート、面接などについて相談できます。

また、筑波大学には卒業生・修了生による社会人メンターの取り組みがあり、業界研究や企業研究、OB・OG訪問などの相談につなげられます。

## 大学3年生：インターンと選考を本格化する

就職を希望する場合、3年生が本格的な活動の開始時期です。

特に夏のインターンへ参加したい場合は、3年生の4月から6月ごろに準備を始めます。

企業によって募集時期は異なるため、興味のある企業については早めに採用ページを確認しましょう。

### 3年生の春：就活の土台を作る

4月から6月ごろは、自己分析、業界研究、エントリーシート作成を進めます。

春の準備リスト

- 就活用のメールアドレスを整える
- 就活サイトや企業の採用ページへ登録する
- 自己分析を行う
- 学生時代に取り組んだことを整理する
- エントリーシートの基本形を作る
- Webテストの対策を始める
- 夏インターンへ応募する

自己分析では、「自分はコミュニケーション能力が高い」といった抽象的な表現だけで終わらせないことが重要です。

過去の経験について、次の順番で整理してみましょう。

1. どのような状況だったか
2. どのような課題があったか
3. 自分は何を考えて行動したか
4. どのような結果になったか
5. その経験から何を学んだか

授業、研究、サークル、アルバイト、学生団体など、題材は何でも構いません。企業が見ているのは、経験の派手さだけではなく、その人がどのように考えて行動したかです。

### 3年生の夏：インターンに参加する

夏休みには、興味のある企業や業界のインターンへ参加します。

応募数をむやみに増やす必要はありません。最初は、本当に興味のある企業を中心に5社から10社程度選び、応募書類を改善しながら進める方法がおすすめです。

夏の準備リスト

- インターンの選考を受ける
- Webテストや面接を経験する
- 興味のある仕事を実際に確認する
- 社員や参加学生と話す
- 参加後に感じたことを記録する

インターン参加後は、「楽しかった」「大変だった」だけで終わらせず、仕事内容、社員の雰囲気、働き方、自分との相性を記録しておきましょう。

この記録が、秋以降に企業を比較する際の判断材料になります。

### 3年生の秋・冬：志望先を絞り、早期選考へ備える

秋から冬にかけては、夏の経験をもとに志望業界や企業を絞っていきます。

企業によっては、秋冬インターンや早期選考が行われます。

秋・冬の準備リスト

- 夏インターンの経験を振り返る
- 志望業界を2、3分野に整理する
- 企業ごとの違いを比較する
- 秋冬インターンへ応募する
- エントリーシートを改善する
- 模擬面接を受ける
- 選考と試験期間の予定を調整する

この時期は、授業の課題や試験と就活が重なりやすくなります。

すべての説明会や選考へ参加するのではなく、「志望度が高い」「仕事内容を詳しく知りたい」など、参加する目的を明確にしましょう。

## 大学4年生：選考と卒業研究を両立する

4年生になると、本選考が本格化します。

一方で、ゼミ、研究室、卒業研究も忙しくなります。就活だけを優先して研究室への連絡を後回しにすると、当然ながら予定は衝突します。カレンダーは人間の都合を察して勝手に調整してくれません。

### 4年生の準備リスト

- 志望企業の応募締切を一覧化する
- 週ごとに応募企業数を決める
- 面接内容を毎回記録する
- 研究室の予定を先に確認する
- 指導教員へ就活状況を早めに共有する
- 内定後も卒業要件を確認する

選考が重なる時期は、一日に複数の予定を入れ過ぎないことも重要です。

特に筑波大学から東京都内の対面面接や説明会へ向かう場合、移動時間を含めると半日以上かかることがあります。

可能な場合はオンライン説明会を活用し、対面予定は同じ日にまとめるなど、移動の負担を減らしましょう。

## 大学院進学を考えている場合はどうする？

大学院への進学を考えている場合も、2、3年生のうちから就職と進学の両方を調べておくことが大切です。

「就活をしたくないから大学院へ行く」という決め方ではなく、研究したいテーマ、身につけたい専門性、卒業後の進路を整理した上で判断しましょう。

修士課程で就職する場合は、基本的に次のように考えます。

- 学群4年生から修士1年生前半：研究と業界研究を進める
- 修士1年生の夏：インターンへ参加する
- 修士1年生の秋・冬：早期選考や本選考の準備をする
- 修士2年生：選考と修士論文を両立する

研究職や技術職では、研究内容を分かりやすく説明する力も重要です。

専門用語を並べるのではなく、「何を解決する研究なのか」「自分はどの部分を担当したのか」「社会でどう活用できるのか」を、専門外の人にも伝えられるように準備しておきましょう。

## 授業・研究と就活を両立する3つのコツ

### 1．就活の時間を週に2回だけ確保する

毎日就活サイトを確認すると、時間だけでなく気持ちまで消耗します。

例えば、火曜日と土曜日の夜にそれぞれ90分確保し、その時間だけ応募や企業研究を進めます。

通知を見てその都度対応するのではなく、就活の時間をあらかじめ予定に入れておく方が、授業にも集中しやすくなります。

### 2．試験期間と研究の繁忙期を先に登録する

企業の予定を入れる前に、試験、レポート、学会、研究発表などの日程をカレンダーへ登録しましょう。

忙しい時期は応募数を減らし、長期休暇中に説明会や面接対策をまとめて進めます。

就活を常に同じペースで続ける必要はありません。大学の予定に合わせて、活動量を増減させて問題ありません。

### 3．一人で完成させようとしない

エントリーシートや面接は、一人で考え続けるより、第三者から意見をもらう方が改善しやすくなります。

友人、先輩、研究室の卒業生、キャリア支援チームなどを活用しましょう。

筑波大学のキャリア支援チームでは、個別相談に加えて、エントリーシート、履歴書、面接などの実践的な相談にも対応しています。

## まずは今月、一つだけ行動してみよう

就活準備で重要なのは、最初からすべてを完璧に進めることではありません。

学年に応じて、今月取り組むことを一つ決めてみましょう。

1年生なら、興味のある授業や活動へ参加する。

2年生なら、気になる仕事を三つ調べる。

3年生なら、エントリーシートを一本作る。

4年生なら、応募予定と研究予定を一つのカレンダーにまとめる。

就活は、周囲より早く始めた人が必ず成功する競争ではありません。

自分の経験を振り返り、仕事について知り、納得できる進路を選ぶための活動です。

筑波大学での授業、研究、課外活動も、すべて将来を考える材料になります。

焦って大学生活を就活だけで埋めるのではなく、自分の学年と状況に合った準備から始めていきましょう。
